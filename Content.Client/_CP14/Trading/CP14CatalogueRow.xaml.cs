using Content.Shared._CP14.Trading.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._CP14.Trading;

[GenerateTypedNameReferences]
public sealed partial class CP14CatalogueRow : ContainerButton
{
    public readonly CP14TradingPositionPrototype Position;
    private readonly string _name;
    private readonly string _supplier;
    private readonly int? _cost;
    private readonly bool _unlocked;

    public CP14CatalogueRow(CP14TradingPositionPrototype position, Texture art, string name, string supplier, int? cost, bool unlocked)
    {
        RobustXamlLoader.Load(this);
        Position = position;
        _name = name;
        _supplier = supplier;
        _cost = cost;
        _unlocked = unlocked;
        Art.Texture = art;
        ItemName.Text = name;
        Supplier.Text = unlocked ? supplier : Loc.GetString("cp14-catalogue-locked-row",
            ("supplier", supplier), ("rep", position.ReputationLevel.ToString()));
        Price.Text = cost is { } value ? Loc.GetString("cp14-catalogue-copper", ("amount", value))
            : Loc.GetString("cp14-catalogue-unpriced");
        if (!unlocked)
            Supplier.FontColorOverride = Color.FromHex("#e6bc85");

        ToolTip = name + "\n" + Supplier.Text;
    }

    public bool Matches(string query, string? supplier, int? budget)
    {
        return (supplier == null || Position.Faction.Id == supplier)
            && (budget == null || _unlocked && _cost <= budget)
            && (_name.Contains(query, StringComparison.CurrentCultureIgnoreCase)
                || _supplier.Contains(query, StringComparison.CurrentCultureIgnoreCase));
    }
}
