namespace Content.Client._CP14.Trading;

[GenerateTypedNameReferences]
public sealed partial class CP14TradingPlatformWindow : DefaultWindow
{
    [Dependency] private readonly IPrototypeManager _proto = default!;
    [Dependency] private readonly IEntityManager _entities = default!;
    [Dependency] private readonly IPlayerManager _players = default!;
    [Dependency] private readonly IGameTiming _timing = default!;

    private readonly CP14ClientTradingPlatformSystem _trading;
    private readonly SpriteSystem _sprites;
    private readonly CP14PriceControl _fundsView = new(0);
    private readonly CP14PriceControl _priceView = new(0);
    private readonly Dictionary<ProtoId<CP14TradingFactionPrototype>, FixedPoint2> _reputations = new();
    private readonly Dictionary<ProtoId<CP14TradingPositionPrototype>, int> _prices = new();
    private readonly Dictionary<string, CP14CatalogueRow> _rows = new();
    private CP14TradingPlatformUiState? _state;
    private CP14TradingPlatformComponent? _platform;
    private CP14TradingPositionPrototype? _selection;
    private string? _supplier;
    private TimeSpan _nextRefresh;
    private bool _coolingDown;

    public event Action<ProtoId<CP14TradingPositionPrototype>>? OnBuy;

    public CP14TradingPlatformWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _trading = _entities.System<CP14ClientTradingPlatformSystem>();
        _sprites = _entities.System<SpriteSystem>();
        WalletArt.Texture = _sprites.Frame0(new SpriteSpecifier.Rsi(new ResPath("_CP14/Objects/Economy/wallet.rsi"), "wallet-3"));
        FundsHolder.AddChild(_fundsView);
        PriceHolder.AddChild(_priceView);
        Search.OnTextChanged += _ =>
        {
            ClearSearch.Disabled = Search.Text.Length == 0;
            StockScroll.VScrollTarget = 0;
            RefreshListings();
        };
        ClearSearch.OnPressed += _ =>
        {
            Search.SetText(string.Empty, true);
            Search.GrabKeyboardFocus();
        };
        AvailableOnly.OnToggled += _ => RefreshListings();
        Suppliers.OnItemSelected += args =>
        {
            Suppliers.SelectId(args.Id);
            _supplier = (string?) Suppliers.SelectedMetadata;
            RefreshListings();
        };
        BuyButton.OnPressed += _ =>
        {
            if (!BuyButton.Disabled && _selection != null)
                OnBuy?.Invoke(_selection.ID);
        };
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        _proto.PrototypesReloaded += OnPrototypesReloaded;
    }

    protected override void ExitedTree()
    {
        _proto.PrototypesReloaded -= OnPrototypesReloaded;
        base.ExitedTree();
    }

    private void OnPrototypesReloaded(PrototypesReloadedEventArgs args)
    {
        if (args.WasModified<CP14TradingPositionPrototype>() || args.WasModified<CP14TradingFactionPrototype>())
            RefreshMarket(true);
    }

    public void UpdateState(CP14TradingPlatformUiState state)
    {
        var first = _state == null;
        _state = state;
        _fundsView.SetPrice(state.Funds);
        if (RefreshMarket(first))
            return;

        if (AvailableOnly.Pressed)
            RefreshListings();
        else
            UpdateCheckout();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (_state == null || _timing.RealTime < _nextRefresh)
            return;

        // Reputation and the station price sheet replicate separately from the platform balance.
        _nextRefresh = _timing.RealTime + TimeSpan.FromMilliseconds(250);
        RefreshMarket(false);
        if (IsCoolingDown() != _coolingDown)
            UpdateCheckout();
    }

    private bool RefreshMarket(bool force)
    {
        if (_state == null)
            return false;

        var previousPlatform = _platform;
        _entities.TryGetComponent(_entities.GetEntity(_state.Platform), out _platform);
        _entities.TryGetComponent<CP14TradingReputationComponent>(_players.LocalEntity, out var user);
        var markets = _entities.AllEntityQueryEnumerator<CP14StationEconomyComponent>();
        markets.MoveNext(out _, out var market);

        if (!force && previousPlatform == _platform && (user == null ? _reputations.Count == 0 : _reputations.SequenceEqual(user.Reputation))
                   && (market == null ? _prices.Count == 0 : _prices.SequenceEqual(market.Pricing)))
            return false;

        _reputations.Clear();
        if (user != null)
        {
            foreach (var (faction, rep) in user.Reputation)
                _reputations.Add(faction, rep);
        }

        _prices.Clear();
        if (market != null)
        {
            foreach (var (position, price) in market.Pricing)
                _prices.Add(position, price);
        }

        Suppliers.Clear();
        Suppliers.AddItem(Loc.GetString("cp14-catalogue-all"));
        var selectedIndex = 0;
        foreach (var faction in _proto.EnumeratePrototypes<CP14TradingFactionPrototype>()
                     .Where(f => _reputations.ContainsKey(f.ID))
                     .OrderBy(f => Loc.GetString(f.Name), StringComparer.CurrentCultureIgnoreCase))
        {
            Suppliers.AddItem(Loc.GetString(faction.Name));
            var index = Suppliers.ItemCount - 1;
            Suppliers.SetItemMetadata(index, faction.ID);
            if (faction.ID == _supplier)
                selectedIndex = index;
        }
        Suppliers.Select(selectedIndex);
        _supplier = (string?) Suppliers.SelectedMetadata;
        BuildRows();
        RefreshListings();
        return true;
    }

    private int? Price(CP14TradingPositionPrototype position)
    {
        if (_platform == null || !_prices.TryGetValue(position.ID, out var price))
            return null;

        // Coins are indivisible. A fractional public price requires the next whole copper.
        return (int) MathF.Ceiling(price * _platform.PlatformMarkupProcent);
    }

    private void BuildRows()
    {
        Stock.RemoveAllChildren();
        _rows.Clear();
        var listings = _proto.EnumeratePrototypes<CP14TradingPositionPrototype>()
            .Where(p => _reputations.ContainsKey(p.Faction))
            .Select(p => (Position: p, Name: _trading.GetTradeName(p), Supplier: Loc.GetString(_proto.Index(p.Faction).Name),
                Unlocked: _reputations[p.Faction] >= p.ReputationLevel, Price: Price(p)))
            .OrderByDescending(x => x.Unlocked)
            .ThenBy(x => x.Name, StringComparer.CurrentCultureIgnoreCase)
            .ThenBy(x => x.Supplier, StringComparer.CurrentCultureIgnoreCase)
            .ThenBy(x => x.Position.ID, StringComparer.Ordinal);

        foreach (var entry in listings)
        {
            var position = entry.Position;
            var row = new CP14CatalogueRow(position, _sprites.Frame0(position.Icon), entry.Name, entry.Supplier, entry.Price, entry.Unlocked);
            row.OnPressed += _ => SelectItem(position);
            Stock.AddChild(row);
            _rows.Add(position.ID, row);
        }
    }

    private void RefreshListings()
    {
        var query = Search.Text.Trim();
        var budget = AvailableOnly.Pressed ? _state?.Funds : null;
        CP14TradingPositionPrototype? selected = null;
        var count = 0;
        foreach (var row in _rows.Values)
        {
            row.Visible = row.Matches(query, _supplier, budget);
            if (!row.Visible)
                continue;

            count++;
            if (selected == null || row.Position.ID == _selection?.ID)
                selected = row.Position;
        }

        Results.Text = Loc.GetString("cp14-catalogue-results", ("count", count));
        NoResults.Visible = count == 0;
        NoResults.SetMessage(Loc.GetString(_reputations.Count == 0 ? "cp14-catalogue-no-contracts" : "cp14-catalogue-no-results"));
        SelectItem(selected);
    }

    private void SelectItem(CP14TradingPositionPrototype? position)
    {
        if (_selection != null && _rows.TryGetValue(_selection.ID, out var previous))
            previous.Pressed = false;
        _selection = position;
        Details.Visible = position != null;
        if (position != null)
        {
            _rows[position.ID].Pressed = true;
            ItemArt.Texture = _sprites.Frame0(position.Icon);
            ItemName.SetMessage(_trading.GetTradeName(position));
            ItemSupplier.SetMessage(Loc.GetString(_proto.Index(position.Faction).Name), defaultColor: Color.FromHex("#e6c995"));
            ItemDescription.SetMessage(_trading.GetTradeDescription(position));
            Reputation.SetMessage(Loc.GetString("cp14-catalogue-reputation",
                ("current", _reputations[position.Faction].ToString()), ("required", position.ReputationLevel.ToString())));
        }
        UpdateCheckout();
    }

    private bool IsCoolingDown() => _platform != null && _timing.CurTime < _platform.NextBuyTime;

    private void UpdateCheckout()
    {
        _coolingDown = IsCoolingDown();
        BuyButton.Disabled = true;
        if (_selection == null || _state == null)
            return;

        var price = Price(_selection);
        PriceHolder.Visible = price.HasValue;
        _priceView.SetPrice(price ?? 0);
        string? status = null;
        if (price == null)
            status = Loc.GetString("cp14-catalogue-unpriced");
        else if (_reputations[_selection.Faction] < _selection.ReputationLevel)
            status = Loc.GetString("cp14-catalogue-earn-rep");
        else if (price > _state.Funds)
            status = Loc.GetString("cp14-catalogue-shortfall", ("amount", price.Value - _state.Funds));
        else if (_coolingDown)
            status = Loc.GetString("cp14-catalogue-wait");

        BuyStatus.Visible = status != null;
        BuyStatus.SetMessage(status ?? string.Empty);
        BuyButton.Disabled = status != null;
    }
}
