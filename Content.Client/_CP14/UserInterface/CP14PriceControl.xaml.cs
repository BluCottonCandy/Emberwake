using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._CP14.UserInterface;

[GenerateTypedNameReferences]
public sealed partial class CP14PriceControl : Control
{
    [Dependency] private readonly IEntityManager _entity = default!;

    public CP14PriceControl(int price)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        var sprite = _entity.System<SpriteSystem>();

        var rsiPath = new ResPath("_CP14/Interface/Misc/coins.rsi");

        SetPrice(price);

        CopperView.Texture = sprite.Frame0(new SpriteSpecifier.Rsi(rsiPath, "c"));
        SilverView.Texture = sprite.Frame0(new SpriteSpecifier.Rsi(rsiPath, "s"));
        GoldView.Texture = sprite.Frame0(new SpriteSpecifier.Rsi(rsiPath, "g"));
    }

    public void SetPrice(int price)
    {
        GoldText.Text = (price / 100).ToString();
        SilverText.Text = (price / 10 % 10).ToString();
        CopperText.Text = (price % 10).ToString();
    }
}
